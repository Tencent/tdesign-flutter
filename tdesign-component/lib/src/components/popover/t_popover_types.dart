/// 弹出气泡预设配色。
enum TPopoverColorScheme {
  /// 默认深色配色。
  defaultTheme,

  /// 浅色。
  light,

  /// 品牌主色。
  primary,

  /// 成功。
  success,

  /// 警告。
  warning,

  /// 危险色。
  danger,
}

/// 气泡弹层定位方向。
enum TPopoverPlacement {
  /// 上左。
  topLeft,

  /// 上方。
  top,

  /// 上右。
  topRight,

  /// 右上。
  rightTop,

  /// 右侧。
  right,

  /// 右下。
  rightBottom,

  /// 下右。
  bottomRight,

  /// 下方。
  bottom,

  /// 下左。
  bottomLeft,

  /// 左下。
  leftBottom,

  /// 左侧。
  left,

  /// 左上。
  leftTop,
}
