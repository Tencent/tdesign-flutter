/// 头像尺寸。
enum TAvatarSize {
  /// 大尺寸。
  large,

  /// 中尺寸。
  medium,

  /// 小尺寸。
  small,
}

/// 头像形状。
enum TAvatarShape {
  /// 圆形头像。
  circle,

  /// 方形头像。
  square,
}

/// 头像形状的旧命名。
enum TAvatarVariant {
  /// 圆形头像。
  circle,

  /// 圆角方形头像。
  square,
}

/// 头像组的层叠方向。
enum TAvatarGroupCascading {
  /// 起始侧头像位于上层。
  startUp,

  /// 结束侧头像位于上层。
  endUp,
}
