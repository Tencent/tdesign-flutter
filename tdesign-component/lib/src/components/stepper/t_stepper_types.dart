/// 步进器尺寸。
enum TStepperSize {
  /// 小尺寸：控件高度 20，输入段宽度 34，图标尺寸 12。
  small,

  /// 中尺寸：控件高度 24，输入段宽度 38，图标尺寸 16。
  ///
  /// 这是默认尺寸。
  medium,

  /// 大尺寸：控件高度 26，输入段宽度 45，图标尺寸 20。
  large,
}

/// 步进器形态。
enum TStepperVariant {
  /// 透明分段形态，段间默认保留 4px 间距。
  ///
  /// 这是默认形态。
  normal,

  /// 填充分段形态，三段使用背景色并保留默认 4px 间距。
  filled,

  /// 连续描边形态，三段之间不保留间距。
  outline,
}
